const originalText = new WeakMap<Node,string>()
const lastApplied = new WeakMap<Node,string>()
const originalAttrs = new WeakMap<Element,Record<string,string>>()

function translateDynamic(value:string, lang:Language) {
  if(lang==='en') return value
  const dict=dictionaries[lang]
  const trimmed=value.trim()
  if(dict[trimmed]) return value.replace(trimmed,dict[trimmed])
  const chapter=trimmed.match(/^Chapter\s+(\d+)$/i)
  if(chapter) return value.replace(trimmed,`Capítulo ${chapter[1]}`)
  const displays=trimmed.match(/^(\d+)\s+displays?\s+detected$/i)
  if(displays) return value.replace(trimmed,lang==='pt'?`${displays[1]} tela(s) detectada(s)`:`${displays[1]} pantalla(s) detectada(s)`)
  const items=trimmed.match(/^(\d+)\s+items$/i)
  if(items) return value.replace(trimmed,lang==='pt'?`${items[1]} itens`:`${items[1]} elementos`)
  if(lang==='pt') return value.replace(/Loading…/g,'Carregando…').replace(/Not installed/g,'Não instalado').replace(/Running/g,'Executando')
  return value.replace(/Loading…/g,'Cargando…').replace(/Not installed/g,'No instalado').replace(/Running/g,'Ejecutando')
}

function applyText(node:Node,lang:Language){
  if(node.parentElement?.closest('[data-no-translate="true"]')) return
  const current=node.nodeValue||''
  const last=lastApplied.get(node)
  if(!originalText.has(node) || (last!==undefined && current!==last)) originalText.set(node,current)
  const canonical=originalText.get(node)||current
  const translated=translateDynamic(canonical,lang)
  if(current!==translated) node.nodeValue=translated
  lastApplied.set(node,translated)
}

function applyAttrs(el:Element,lang:Language){
  if(el.closest('[data-no-translate="true"]')) return
  let originals=originalAttrs.get(el)
  if(!originals){ originals={}; originalAttrs.set(el,originals) }
  for(const attr of ['placeholder','title','aria-label']){
    if(!el.hasAttribute(attr)) continue
    const current=el.getAttribute(attr)||''
    if(!(attr in originals)) originals[attr]=current
    const translated=translateDynamic(originals[attr],lang)
    // MutationObserver watches these same attributes. Writing an unchanged
    // value can schedule another attribute mutation and create a feedback
    // loop that starves React/Electron input handling.
    if(current!==translated) el.setAttribute(attr,translated)
  }
}

function translateTree(root:Node,lang:Language){
  if(root.nodeType===Node.TEXT_NODE){applyText(root,lang);return}
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT)
  let n:Node|null
  while((n=walker.nextNode())) applyText(n,lang)
  if(root instanceof Element) applyAttrs(root,lang)
  if(root instanceof Document || root instanceof Element) root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach(el=>applyAttrs(el,lang))
}

export function installDomTranslation(lang:Language){
  document.documentElement.lang=lang==='pt'?'pt-BR':lang==='es'?'es':'en'
  translateTree(document.body,lang)
  const observer=new MutationObserver(mutations=>{
    for(const mutation of mutations){
      if(mutation.type==='characterData') applyText(mutation.target,lang)
      mutation.addedNodes.forEach(node=>translateTree(node,lang))
      if(mutation.type==='attributes' && mutation.target instanceof Element) applyAttrs(mutation.target,lang)
    }
  })
  observer.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','title','aria-label']})
  return ()=>observer.disconnect()
}
